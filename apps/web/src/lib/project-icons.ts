export type ProjectIconKey = keyof typeof PROJECT_ICONS;

export function isProjectIconKey(value: string): value is ProjectIconKey {
  return Object.hasOwn(PROJECT_ICONS, value);
}

export function getProjectIcon(icon: string | null | undefined) {
  if (icon && isProjectIconKey(icon)) return PROJECT_ICONS[icon];
  return PROJECT_ICONS.Layout;
}
